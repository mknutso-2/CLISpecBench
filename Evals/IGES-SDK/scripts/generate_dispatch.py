"""Generate src/json/dispatch.cpp for the IGES reference implementation.

Walks Evals/IGES-SDK/src/entities/*.hpp and produces three big switch
statements keyed by IGES type number:

  * parse_entity_dispatch  — (type, form, tok) → nlohmann::json
  * write_entity_dispatch  — (type, form, json) → PD string
  * evaluate_entity_dispatch — (type, form, json, t[, s]) → EvalResult

Detects which parse/write functions take `int form` by scanning the
header signatures. Detects `evaluate(Real t)` / `evaluate(Real u, Real v)`
member functions to populate the eval table.

Run:
    python Evals/IGES-SDK/scripts/generate_dispatch.py \
        > Evals/IGES/reference-implementation-cpp/src/json/dispatch.cpp
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

ENTITIES_DIR = Path(__file__).resolve().parents[1] / "src" / "entities"
WRITER_HPP = Path(__file__).resolve().parents[1] / "src" / "writer" / "entity_writer.hpp"
EXCLUDE = {"entity.hpp"}


HEADER_RE = re.compile(r"//\s*iges::(?P<name>\w+Entity)\s+[—-]\s+Type[s]?\s+(?P<types>[\d, /]+)")
PARSE_RE = re.compile(r"^(?P<fn>parse_\w+_entity)\s*\(\s*ParamTokenizer&\s+tok(?P<rest>[^)]*)\)", re.MULTILINE)
EVAL_CURVE_RE = re.compile(r"\bVec3\s+evaluate\s*\(\s*Real\s+\w+\s*\)\s*const")
EVAL_SURFACE_RE = re.compile(r"\bVec3\s+evaluate\s*\(\s*Real\s+\w+\s*,\s*Real\s+\w+\s*\)\s*const")


@dataclass
class Entity:
    filename: str      # e.g. "line_entity.hpp"
    stem: str          # e.g. "line_entity"
    cxx_name: str      # e.g. "LineEntity"
    type_number: int
    parse_takes_form: bool
    writer_takes_form: bool
    eval_kind: str     # "curve", "surface", or "none"


def load_entity(path: Path) -> Entity | None:
    source = path.read_text(encoding="utf-8")
    m = HEADER_RE.search(source)
    if not m:
        return None
    # Pick primary type number (first number in the list)
    nums = re.findall(r"\d+", m.group("types"))
    if not nums:
        return None
    type_num = int(nums[0])

    # Parse signature: does it take `int form`?
    parse_takes_form = False
    pm = PARSE_RE.search(source)
    if pm and "int form" in pm.group("rest"):
        parse_takes_form = True

    # Evaluate support
    if EVAL_SURFACE_RE.search(source):
        eval_kind = "surface"
    elif EVAL_CURVE_RE.search(source):
        eval_kind = "curve"
    else:
        eval_kind = "none"

    return Entity(
        filename=path.name,
        stem=path.stem,
        cxx_name=m.group("name"),
        type_number=type_num,
        parse_takes_form=parse_takes_form,
        writer_takes_form=False,  # filled in from entity_writer.hpp
        eval_kind=eval_kind,
    )


def load_writer_form_set() -> set[str]:
    """Return stems of entities whose write_*_entity takes `int form`."""
    source = WRITER_HPP.read_text(encoding="utf-8")
    out: set[str] = set()
    for m in re.finditer(
        r"write_(?P<stem>\w+_entity)\s*\([^)]*\bint\s+form\b", source
    ):
        # "stem" is the writer function stem — same as the entity file stem,
        # except for a few naming quirks (see mapping table below).
        out.add(m.group("stem"))
    return out


# Writer function stem → entity file stem (only needed when the writer
# function name does not match the .hpp filename).
# In the current SDK all writer stems match entity file stems exactly.
STEM_MAP: dict[str, str] = {}


def writer_fn(stem: str) -> str:
    return f"write_{STEM_MAP.get(stem, stem)}"


def parse_fn(stem: str) -> str:
    return f"parse_{stem}"


HEADER = """\
// AUTO-GENERATED by Evals/IGES-SDK/scripts/generate_dispatch.py
// Do not edit by hand — regenerate after adding an entity.

#include "dispatch.hpp"
#include "entity_json.hpp"
#include "eval_helpers.hpp"

// Parser signatures
"""


# Types whose evaluator depends on other entities by DE pointer — their
# eval cases dispatch to hand-written free functions in eval_helpers.cpp
# rather than to an entity member function. Keys map to (helper_stem,
# kind) where kind is "curve" or "surface".
RESOLVER_USING: dict[int, tuple[str, str]] = {
    102: ("composite_curve", "curve"),
}


def emit_parser_includes(entities: list[Entity]) -> str:
    lines: list[str] = []
    for e in entities:
        lines.append(f'#include "../entities/{e.filename}"')
    lines.append('#include "../writer/entity_writer.hpp"')
    return "\n".join(lines)


def emit_parse_dispatch(entities: list[Entity]) -> str:
    lines: list[str] = [
        "std::expected<nlohmann::json, Diagnostic>",
        "parse_entity_dispatch(int type, int form, ParamTokenizer& tok) {",
        "    switch (type) {",
    ]
    for e in entities:
        call = f"{parse_fn(e.stem)}(tok"
        if e.parse_takes_form:
            call += ", form"
        call += ")"
        lines.append(f"    case {e.type_number}: {{")
        lines.append(f"        auto r = {call};")
        lines.append(f"        if (!r) return std::unexpected(r.error());")
        lines.append(f"        nlohmann::json j = *r;")
        lines.append(f"        return j;")
        lines.append(f"    }}")
    lines.append("    default:")
    lines.append("        return std::unexpected(Diagnostic{")
    lines.append("            Diagnostic::Severity::Error, 0, SectionKind::Parameter,")
    lines.append('            std::string{"Unsupported entity type: "} + std::to_string(type),')
    lines.append('            "§3.2"})')
    lines.append("        ;")
    lines.append("    }")
    lines.append("    (void)form;")
    lines.append("}")
    return "\n".join(lines)


def emit_write_dispatch(entities: list[Entity]) -> str:
    lines: list[str] = [
        "std::expected<std::string, Diagnostic>",
        "write_entity_dispatch(int type, int form, nlohmann::json const& data) {",
        "    try {",
        "        switch (type) {",
    ]
    for e in entities:
        cxx = e.cxx_name
        writer = writer_fn(e.stem)
        lines.append(f"        case {e.type_number}: {{")
        lines.append(f"            auto ent = data.get<iges::{cxx}>();")
        if e.writer_takes_form:
            lines.append(f"            return iges::{writer}(ent, form);")
        else:
            lines.append(f"            (void)form;")
            lines.append(f"            return iges::{writer}(ent);")
        lines.append(f"        }}")
    lines.append("        default:")
    lines.append("            return std::unexpected(Diagnostic{")
    lines.append("                Diagnostic::Severity::Error, 0, SectionKind::Parameter,")
    lines.append('                std::string{"Unsupported entity type: "} + std::to_string(type),')
    lines.append('                "§3.2"})')
    lines.append("            ;")
    lines.append("        }")
    lines.append("    } catch (nlohmann::json::exception const& ex) {")
    lines.append("        return std::unexpected(Diagnostic{")
    lines.append("            Diagnostic::Severity::Error, 0, SectionKind::Parameter,")
    lines.append('            std::string{"JSON deserialization failed: "} + ex.what(),')
    lines.append('            "§2"});')
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines)


def emit_evaluate_dispatch(entities: list[Entity]) -> str:
    lines: list[str] = [
        "std::expected<EvalResult, Diagnostic>",
        "evaluate_entity_dispatch(int type, int form, nlohmann::json const& data,",
        "                         Real t, std::optional<Real> s,",
        "                         EntityResolver const& resolver) {",
        "    (void)form;",
        "    (void)resolver;  // unused by simple self-contained evaluators",
        "    try {",
        "        switch (type) {",
    ]
    for e in entities:
        cxx = e.cxx_name
        resolver_entry = RESOLVER_USING.get(e.type_number)
        if resolver_entry is not None:
            helper_stem, kind = resolver_entry
            lines.append(f"        case {e.type_number}: {{")
            lines.append(f"            auto ent = data.get<iges::{cxx}>();")
            if kind == "curve":
                lines.append(f"            if (s.has_value()) return std::unexpected(Diagnostic{{")
                lines.append(f"                Diagnostic::Severity::Error, 0, SectionKind::Parameter,")
                lines.append(f'                "Curve entity does not accept --s", "§1"}});')
                lines.append(f"            return iges::evaluate_{helper_stem}(ent, t, resolver);")
            else:  # surface
                lines.append(f"            if (!s.has_value()) return std::unexpected(Diagnostic{{")
                lines.append(f"                Diagnostic::Severity::Error, 0, SectionKind::Parameter,")
                lines.append(f'                "Surface entity requires --s", "§1"}});')
                lines.append(f"            return iges::evaluate_{helper_stem}(ent, t, *s, resolver);")
            lines.append(f"        }}")
            continue

        if e.eval_kind == "none":
            continue
        lines.append(f"        case {e.type_number}: {{")
        lines.append(f"            auto ent = data.get<iges::{cxx}>();")
        if e.eval_kind == "curve":
            lines.append(f"            if (s.has_value()) return std::unexpected(Diagnostic{{")
            lines.append(f"                Diagnostic::Severity::Error, 0, SectionKind::Parameter,")
            lines.append(f'                "Curve entity does not accept --s", "§1"}});')
            lines.append(f"            EvalResult r;")
            lines.append(f"            r.point = ent.evaluate(t);")
            lines.append(f"            return r;")
        else:  # surface
            lines.append(f"            if (!s.has_value()) return std::unexpected(Diagnostic{{")
            lines.append(f"                Diagnostic::Severity::Error, 0, SectionKind::Parameter,")
            lines.append(f'                "Surface entity requires --s", "§1"}});')
            lines.append(f"            EvalResult r;")
            lines.append(f"            r.point = ent.evaluate(t, *s);")
            lines.append(f"            return r;")
        lines.append(f"        }}")
    lines.append("        default:")
    lines.append("            return std::unexpected(Diagnostic{")
    lines.append("                Diagnostic::Severity::Error, 0, SectionKind::Parameter,")
    lines.append('                std::string{"Entity type "} + std::to_string(type) + " is not parametric",')
    lines.append('                "§1"});')
    lines.append("        }")
    lines.append("    } catch (nlohmann::json::exception const& ex) {")
    lines.append("        return std::unexpected(Diagnostic{")
    lines.append("            Diagnostic::Severity::Error, 0, SectionKind::Parameter,")
    lines.append('            std::string{"JSON deserialization failed: "} + ex.what(),')
    lines.append('            "§2"});')
    lines.append("    }")
    lines.append("    (void)t; (void)s;")
    lines.append("}")
    return "\n".join(lines)


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]

    writer_form_stems = load_writer_form_set()

    entities: list[Entity] = []
    for path in sorted(ENTITIES_DIR.glob("*.hpp")):
        if path.name in EXCLUDE:
            continue
        e = load_entity(path)
        if e is None:
            print(f"WARN: no header info in {path.name}", file=sys.stderr)
            continue
        e.writer_takes_form = e.stem in writer_form_stems
        entities.append(e)

    # Sort by IGES type number for a stable, spec-aligned switch layout.
    entities.sort(key=lambda e: (e.type_number, e.cxx_name))

    out: list[str] = [HEADER]
    out.append(emit_parser_includes(entities))
    out.append("#include <string>")
    out.append("#include <nlohmann/json.hpp>")
    out.append("")
    out.append("namespace iges {")
    out.append("")
    out.append(emit_parse_dispatch(entities))
    out.append("")
    out.append(emit_write_dispatch(entities))
    out.append("")
    out.append(emit_evaluate_dispatch(entities))
    out.append("")
    out.append("} // namespace iges")

    sys.stdout.write("\n".join(out))
    print(f"\n\n// {len(entities)} entities dispatched", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
